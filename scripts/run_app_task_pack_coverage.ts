type Row = {
  kind: "lawful" | "hostile";
  id: string;
  expected: string;
  actual: string;
  status: "survivor" | "caught" | "missed";
  expectedRoot: string;
  actualRoot: string;
  expectedMetaRoot: string;
  actualMetaRoot: string;
};

const QUESTION = "build a next.js app router page with tests";

async function main(): Promise<void> {
  const contract = deriveCodingSkeletonContract({
    question: QUESTION,
    userLaws: [],
    insights: [],
  });
  const intentSpec = deriveCodingIntentSpec({ question: QUESTION, contract });

  const rows: Row[] = [];

  for (const task of getLawfulAppTaskPacks()) {
    const text = buildLawfulTaskCandidate(task.id, task.minimalLawfulBaseline);
    const actual = evaluateText(text, contract, intentSpec);
    const actualClassified = classifyReason(actual);
    rows.push({
      kind: "lawful",
      id: task.id,
      expected: "survivor",
      actual,
      status: actual === "survivor" ? "survivor" : "missed",
      expectedRoot: "survivor",
      actualRoot: actualClassified.root,
      expectedMetaRoot: "survivor",
      actualMetaRoot: actualClassified.metaRoot,
    });
  }

  for (const task of getHostileAppTaskPacks()) {
    const text = buildHostileTaskCandidate(task.id, task.minimalHostileExample);
    const actual = evaluateText(text, contract, intentSpec);
    const expectedClassified = classifyReason(task.targetFailure);
    const actualClassified = classifyReason(actual);
    rows.push({
      kind: "hostile",
      id: task.id,
      expected: task.targetFailure,
      actual,
      status: actual === task.targetFailure || actualClassified.root === expectedClassified.root ? "caught" : "missed",
      expectedRoot: expectedClassified.root,
      actualRoot: actualClassified.root,
      expectedMetaRoot: expectedClassified.metaRoot,
      actualMetaRoot: actualClassified.metaRoot,
    });
  }

  const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, "");
  const reportPath = path.join(process.cwd(), "docs", `CODING_APP_TASK_PACK_COVERAGE_${stamp}.md`);
  await fs.writeFile(reportPath, renderReport(rows), "utf8");
  await appendCodingCoverageLedger("APP_TASK_COVERAGE_COMPLETED", {
    createdAt: new Date().toISOString(),
    reportPath,
    planet: "ability",
    ontologyStatus: "aligned",
    slice: "app_task",
    lawIds: [
      "ABILITY.CODING.147",
      "ABILITY.CODING.148",
      "ABILITY.CODING.149",
      "ABILITY.CODING.150",
      "ABILITY.CODING.151",
    ],
    metrics: {
      lawfulTasks: rows.filter((row) => row.kind === "lawful").length,
      lawfulSurvivors: rows.filter((row) => row.kind === "lawful" && row.status === "survivor").length,
      hostileTasks: rows.filter((row) => row.kind === "hostile").length,
      hostileCaught: rows.filter((row) => row.kind === "hostile" && row.status === "caught").length,
      hostileMissed: rows.filter((row) => row.kind === "hostile" && row.status === "missed").length,
    },
  });
  console.log(reportPath);
}

