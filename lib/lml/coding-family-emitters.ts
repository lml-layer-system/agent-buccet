import type { CodingIntentSpec } from "@/lib/lml/coding-intent-spec";
import type { CodingSkeletonContract } from "@/lib/lml/coding-skeleton-laws";
import { buildCodingProjectGraphs, summarizeCodingProjectGraph } from "@/lib/lml/coding-project-graph";
import { getCodingOracleFamily, hasCodingOracleFamily } from "@/lib/lml/coding-oracle";
import { buildOracleScaffold } from "@/lib/lml/coding-oracle/scaffolds";
import type { CodingBodyFillSlot } from "@/lib/lml/coding-body-fill";

export type DirectCodingEmitterCandidate = {
  id: string;
  label: string;
  text: string;
  slots: CodingBodyFillSlot[];
};

export function buildDirectCodingEmitterCandidates(args: {
  contract: CodingSkeletonContract;
  intentSpec: CodingIntentSpec;
}): DirectCodingEmitterCandidate[] {
  const graphs = buildCodingProjectGraphs(args);
  return graphs.map((graph) => ({
    id: `cand.graph.${graph.family}.${graph.variant}`,
    label: `project_graph_${graph.family}_${graph.variant}`,
    ...buildGraphSkeletonText(graph, args.intentSpec),
  }));
}

function buildGraphSkeletonText(
  graph: ReturnType<typeof buildCodingProjectGraphs>[number],
  intentSpec: CodingIntentSpec,
): { text: string; slots: CodingBodyFillSlot[] } {
  const oracleHeader = buildOracleHeader(graph.family, graph.variant);
  if (
    hasCodingOracleFamily(graph.family)
    && (graph.family === "api" || graph.family === "app" || graph.family === "auth" || graph.family === "compiler" || graph.family === "game" || graph.family === "orm" || graph.family === "refactor")
  ) {
    return prependOracleHeader(
      buildOracleScaffold({
        family: graph.family,
        variant: graph.variant,
        graphSummary: summarizeCodingProjectGraph(graph),
        intentSpec,
      }),
      oracleHeader,
    );
  }
  switch (graph.family) {
    case "parser":
      return buildParserSkeletonText(intentSpec, summarizeCodingProjectGraph(graph), graph.variant);
    default:
      return { text: "", slots: [] };
  }
}

function prependOracleHeader(
  payload: { text: string; slots: CodingBodyFillSlot[] },
  oracleHeader: string,
): { text: string; slots: CodingBodyFillSlot[] } {
  if (!oracleHeader) {
    return payload;
  }
  return {
    ...payload,
    text: `${oracleHeader}\n${payload.text}`,
  };
}

function buildOracleHeader(family: CodingSkeletonContract["family"], variant: string): string {
  if (!hasCodingOracleFamily(family)) {
    return "";
  }
  const oracle = getCodingOracleFamily(family);
  const chosenVariant = oracle.variants.find((candidate) => candidate.id === variant) ?? oracle.variants[0];
  const invariants = oracle.lawfulInvariants.slice(0, 4).map((line) => `# oracle_invariant ${line}`);
  const contracts = oracle.importContracts.slice(0, 3).map((line) => `# oracle_contract ${line.from} -> ${line.to}: ${line.rule}`);
  const header = [
    `# oracle_family ${oracle.family} :: ${oracle.title}`,
    `# oracle_variant ${chosenVariant.id} :: ${chosenVariant.description}`,
    `# oracle_decomposition ${chosenVariant.decompositionRule}`,
    ...invariants,
    ...contracts,
  ];
  return header.join("\n");
}

