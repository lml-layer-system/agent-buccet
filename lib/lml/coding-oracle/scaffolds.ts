import type { CodingIntentSpec } from "../coding-intent-spec.ts";
import type { CodingBodyFillSlot } from "../coding-body-fill.ts";
import type { OracleFamily } from "./types.ts";

export function buildOracleScaffold(args: {
  family: Extract<OracleFamily, "api" | "app" | "auth" | "compiler" | "game" | "orm" | "refactor">;
  variant: string;
  graphSummary: string;
  intentSpec: CodingIntentSpec;
}): { text: string; slots: CodingBodyFillSlot[] } {
  const { family, variant, graphSummary, intentSpec } = args;
  switch (family) {
    case "api":
      return buildApiOracleScaffold(intentSpec, graphSummary, variant);
    case "app":
      return buildAppOracleScaffold(intentSpec, graphSummary, variant);
    case "auth":
      return buildAuthOracleScaffold(intentSpec, graphSummary, variant);
    case "compiler":
      return buildCompilerOracleScaffold(intentSpec, graphSummary, variant);
    case "game":
      return buildGameOracleScaffold(intentSpec, graphSummary, variant);
    case "orm":
      return buildOrmOracleScaffold(intentSpec, graphSummary, variant);
    case "refactor":
      return buildRefactorOracleScaffold(intentSpec, graphSummary, variant);
  }
}

