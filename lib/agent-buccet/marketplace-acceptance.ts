import type { BoundaryActionKind } from "./types.ts";

type TargetMatchMode = "prefix" | "exact" | "regex";

export type MarketplaceAcceptanceLane = {
  id: string;
  source: "skillsmp" | "skillhub" | "aitmpl" | "agentskills";
  name: string;
  summary: string;
  actionKinds: BoundaryActionKind[];
  targetPattern?: string;
  targetPatterns?: string[];
  targetMatchMode?: TargetMatchMode;
  requestTextPatterns?: string[];
  seedInBasePack?: boolean;
};

function namedLane(args: {
  id: string;
  source: MarketplaceAcceptanceLane["source"];
  name: string;
  summary: string;
  actionKinds: BoundaryActionKind[];
  requestTextPatterns?: string[];
  seedInBasePack?: boolean;
}): MarketplaceAcceptanceLane {
  return {
    id: args.id,
    source: args.source,
    name: args.name,
    summary: args.summary,
    actionKinds: args.actionKinds,
    targetPattern: args.name,
    targetMatchMode: "exact",
    requestTextPatterns: args.requestTextPatterns ?? [args.name],
    seedInBasePack: args.seedInBasePack,
  };
}

